#!/usr/bin/env python3
"""Mux small MP4 and WebM fixtures for the container demuxer tests, without FFmpeg.

Requires only Python 3 (standard library). Run from anywhere:
    python fixtures/video/gen_container_fixture.py

The output is deterministic. Nothing is encoded: the video payloads are the
committed elementary streams that the codec tests already use, repackaged:

* container-h264-opus.mp4: ipcm-128x96.h264 (three access units: IDR, P, IDR) as
  AVCC samples in two chunks, with a composition-time offset plus an edit list
  that cancels it, and an Opus track of six 20 ms packets.
* container-h264-aac.mp4: the same video with an AAC (mp4a/esds) track of five
  1024-sample payloads that are not real AAC; the demuxer must report the track
  as unsupported audio, never read it.
* container-h264-aac-lc.mp4: the same video with the genuine AAC-LC frames of
  ../audio/aac-lc-tone.m4a (Windows Media Foundation encoder output, see
  ../audio/gen_aac_tone.py), re-muxed with that file's AudioSpecificConfig.
* container-av1-opus.webm: av1-lossless-420-8.ivf (three temporal units) without
  temporal delimiters, its sequence header as av1C, in two clusters (a
  SimpleBlock and a BlockGroup with a ReferenceBlock) plus an Opus track.

The Opus packets are a 0xF8 table-of-contents byte (CELT fullband, 20 ms, one
frame) and three marker bytes, enough for the demuxer; the manifest records the
SHA-256 of every output. Expected pictures for the AV1 file are the existing
av1-lossless-420-8.nv12 oracle (generated by libaom, see av1-fixture.json).
"""

import hashlib
import json
import pathlib
import struct

HERE = pathlib.Path(__file__).resolve().parent
OPUS_PACKETS = [bytes([0xF8, 0xFF, 0xFE, i]) for i in range(6)]
AAC_PACKETS = [bytes([0x21, i]) + bytes(98) for i in range(5)]
VIDEO_MS = [0, 33, 66]


def u16(v):
    return struct.pack(">H", v)


def u32(v):
    return struct.pack(">I", v)


# ---------------------------------------------------------------- MP4


def box(kind, *parts):
    payload = b"".join(parts)
    return u32(8 + len(payload)) + kind + payload


def full(kind, version, flags, *parts):
    return box(kind, bytes([version]) + flags.to_bytes(3, "big"), *parts)


def split_annexb(data):
    """NAL units of an Annex B stream, in order."""
    out, i, start = [], 0, None
    while i + 3 <= len(data):
        if data[i : i + 3] == b"\x00\x00\x01":
            if start is not None:
                out.append(data[start:i].rstrip(b"\x00"))
            start = i + 3
            i += 3
        else:
            i += 1
    out.append(data[start:].rstrip(b"\x00"))
    return out


def h264_access_units():
    nals = split_annexb((HERE / "ipcm-128x96.h264").read_bytes())
    sps = [n for n in nals if n[0] & 31 == 7][0]
    pps = [n for n in nals if n[0] & 31 == 8][0]
    slices = [n for n in nals if n[0] & 31 in (1, 5)]
    assert len(slices) == 3
    return sps, pps, slices


def trak(track_id, handler, timescale, duration, entry, stts, sizes, chunks, ctts=None,
         stss=None, elst=None, width=0, height=0):
    """chunks: list of (samples_in_chunk, offset)."""
    tkhd = full(
        b"tkhd", 0, 7, u32(0), u32(0), u32(track_id), u32(0), u32(duration), bytes(8),
        u16(0), u16(0), u16(0x0100 if handler == b"soun" else 0), u16(0),
        struct.pack(">9I", 0x10000, 0, 0, 0, 0x10000, 0, 0, 0, 0x40000000),
        u32(width << 16), u32(height << 16),
    )
    mdhd = full(b"mdhd", 0, 0, u32(0), u32(0), u32(timescale), u32(duration), u16(0x55C4), u16(0))
    hdlr = full(b"hdlr", 0, 0, u32(0), handler, bytes(12), b"fixture\x00")
    media_header = (
        full(b"vmhd", 0, 1, bytes(8)) if handler == b"vide" else full(b"smhd", 0, 0, bytes(4))
    )
    dinf = box(b"dinf", full(b"dref", 0, 0, u32(1), full(b"url ", 0, 1)))
    stsd = full(b"stsd", 0, 0, u32(1), entry)
    stts_box = full(b"stts", 0, 0, u32(len(stts)), *[u32(c) + u32(d) for c, d in stts])
    tables = [stsd, stts_box]
    if ctts:
        tables.append(full(b"ctts", 0, 0, u32(len(ctts)), *[u32(c) + u32(o) for c, o in ctts]))
    if stss:
        tables.append(full(b"stss", 0, 0, u32(len(stss)), *[u32(i) for i in stss]))
    # One stsc run per distinct samples-per-chunk value.
    runs, previous = [], None
    for index, (count, _) in enumerate(chunks, 1):
        if count != previous:
            runs.append((index, count))
            previous = count
    tables.append(
        full(b"stsc", 0, 0, u32(len(runs)), *[u32(first) + u32(n) + u32(1) for first, n in runs])
    )
    tables.append(full(b"stsz", 0, 0, u32(0), u32(len(sizes)), *[u32(s) for s in sizes]))
    tables.append(full(b"stco", 0, 0, u32(len(chunks)), *[u32(off) for _, off in chunks]))
    minf = box(b"minf", media_header, dinf, box(b"stbl", *tables))
    parts = [tkhd]
    if elst is not None:
        parts.append(
            box(b"edts", full(b"elst", 0, 0, u32(1), u32(duration), struct.pack(">i", elst),
                              u16(1), u16(0)))
        )
    parts.append(box(b"mdia", mdhd, hdlr, minf))
    return box(b"trak", *parts)


def avc1(sps, pps):
    avcc = box(
        b"avcC", bytes([1, sps[1], sps[2], sps[3], 0xFF, 0xE1]), u16(len(sps)), sps,
        bytes([1]), u16(len(pps)), pps,
    )
    return box(
        b"avc1", bytes(6), u16(1), bytes(16), u16(128), u16(96), u32(0x480000), u32(0x480000),
        u32(0), u16(1), bytes(32), u16(0x18), struct.pack(">h", -1), avcc,
    )


def audio_entry(kind, config_box, rate=48000):
    return box(kind, bytes(6), u16(1), bytes(8), u16(2), u16(16), u16(0), u16(0),
               u32(rate << 16), config_box)


def opus_entry():
    dops = box(b"dOps", bytes([0, 2]), u16(312), u32(48000), struct.pack(">h", 0), bytes([0]))
    return audio_entry(b"Opus", dops)


def aac_entry(asc=bytes([0x12, 0x10]), rate=48000):
    esds = full(
        b"esds", 0, 0,
        bytes([3, 23 + len(asc)]), u16(2), bytes([0]),
        bytes([4, 15 + len(asc), 0x40, 0x15]), bytes(3), u32(0), u32(0),
        bytes([5, len(asc)]), asc, bytes([6, 1, 2]),
    )
    return audio_entry(b"mp4a", esds, rate)


def real_aac():
    """(AudioSpecificConfig, sample rate, frames) of the committed Windows-encoded M4A."""
    data = (HERE.parent / "audio" / "aac-lc-tone.m4a").read_bytes()

    def find(kind, start=0):
        at = data.index(kind, start)
        return at, struct.unpack(">I", data[at - 4:at])[0]

    esds, size = find(b"esds")
    # ES_Descriptor, DecoderConfigDescriptor and DecoderSpecificInfo with 4-byte sizes.
    at = data.index(bytes([5, 0x80, 0x80, 0x80]), esds) + 5
    asc = data[at:at + data[at - 1]]
    stsz, _ = find(b"stsz")
    count = struct.unpack(">I", data[stsz + 12:stsz + 16])[0]
    sizes = struct.unpack(f">{count}I", data[stsz + 16:stsz + 16 + 4 * count])
    stco, _ = find(b"stco")
    assert struct.unpack(">I", data[stco + 8:stco + 12])[0] == 1, "one chunk expected"
    offset = struct.unpack(">I", data[stco + 12:stco + 16])[0]
    frames = []
    for n in sizes:
        frames.append(data[offset:offset + n])
        offset += n
    rate = [96000, 88200, 64000, 48000, 44100, 32000, 24000, 22050][(asc[0] & 7) << 1 | asc[1] >> 7]
    return asc, rate, frames


def mp4(audio):
    sps, pps, slices = h264_access_units()
    avcc_samples = [u32(len(n)) + n for n in slices]
    a_packets = OPUS_PACKETS if audio == "opus" else AAC_PACKETS
    if audio == "aac-lc":
        asc, a_rate, a_packets = real_aac()

    def build(video_offsets, audio_offset):
        v_sizes = [len(s) for s in avcc_samples]
        a_sizes = [len(p) for p in a_packets]
        # 90 kHz video, 3000 ticks per frame; ctts delays everything by 6000 and the
        # edit list takes it back, so the presentation times are 0, 33, 66 ms.
        video = trak(
            1, b"vide", 90000, 9000, avc1(sps, pps), [(3, 3000)], v_sizes,
            [(2, video_offsets[0]), (1, video_offsets[1])], ctts=[(3, 6000)], stss=[1, 3],
            elst=6000, width=128, height=96,
        )
        if audio == "opus":
            sound = trak(2, b"soun", 48000, 5760, opus_entry(), [(6, 960)], a_sizes,
                         [(6, audio_offset)])
        elif audio == "aac-lc":
            n = len(a_packets)
            sound = trak(2, b"soun", a_rate, n * 1024, aac_entry(asc, a_rate), [(n, 1024)],
                         a_sizes, [(n, audio_offset)])
        else:
            sound = trak(2, b"soun", 48000, 5120, aac_entry(), [(5, 1024)], a_sizes,
                         [(5, audio_offset)])
        mvhd = full(
            b"mvhd", 0, 0, u32(0), u32(0), u32(1000), u32(100), u32(0x10000), u16(0x100),
            u16(0), bytes(8), struct.pack(">9I", 0x10000, 0, 0, 0, 0x10000, 0, 0, 0, 0x40000000),
            bytes(24), u32(3),
        )
        return box(b"moov", mvhd, video, sound)

    ftyp = box(b"ftyp", b"isom", u32(512), b"isomiso2avc1mp41")
    size = len(build((0, 0), 0))
    base = len(ftyp) + size + 8
    v0 = base
    a0 = v0 + len(avcc_samples[0]) + len(avcc_samples[1])
    v1 = a0 + sum(len(p) for p in a_packets)
    moov = build((v0, v1), a0)
    assert len(moov) == size
    mdat_payload = (
        avcc_samples[0] + avcc_samples[1] + b"".join(a_packets) + avcc_samples[2]
    )
    return ftyp + moov + box(b"mdat", mdat_payload)


# --------------------------------------------------------------- WebM


def vint_size(n):
    for length in range(1, 9):
        if n < (1 << (7 * length)) - 1:
            return ((1 << (7 * length)) | n).to_bytes(length, "big")
    raise ValueError(n)


def element(ident, payload, fixed8=False):
    size = (b"\x01" + len(payload).to_bytes(7, "big")) if fixed8 else vint_size(len(payload))
    return ident + size + payload


def uint(ident, value):
    return element(ident, value.to_bytes(max(1, (value.bit_length() + 7) // 8), "big"))


def string(ident, value):
    return element(ident, value.encode())


def ivf_units():
    data = (HERE / "av1-lossless-420-8.ivf").read_bytes()
    out, at = [], 32
    while at < len(data):
        (n,) = struct.unpack("<I", data[at : at + 4])
        out.append(data[at + 12 : at + 12 + n])
        at += 12 + n
    return out


def obus(unit):
    at, out = 0, []
    while at < len(unit):
        start = at
        header = unit[at]
        at += 1 + (1 if header & 4 else 0)
        length = shift = 0
        while True:
            byte = unit[at]
            at += 1
            length |= (byte & 127) << shift
            shift += 7
            if byte < 128:
                break
        at += length
        out.append(((header >> 3) & 15, unit[start:at]))
    return out


def simple_block(track, ms, key, payload):
    flags = 0x80 if key else 0
    return element(b"\xA3", bytes([0x80 | track]) + struct.pack(">h", ms) + bytes([flags]) + payload)


def block_group(track, ms, payload):
    block = element(b"\xA1", bytes([0x80 | track]) + struct.pack(">h", ms) + b"\x00" + payload)
    return element(b"\xA0", block + element(b"\xFB", bytes([0xFF])))  # ReferenceBlock -1


def webm():
    units = ivf_units()
    stripped, sequence = [], b""
    for unit in units:
        kept = b""
        for kind, raw in obus(unit):
            if kind == 1:
                sequence = raw
            if kind != 2:
                kept += raw
        stripped.append(kept)
    assert sequence
    av1c = bytes([0x81, 0x00, 0x0C, 0x00]) + sequence
    opus_head = b"OpusHead" + bytes([1, 2]) + struct.pack("<H", 312) + struct.pack("<I", 48000) \
        + struct.pack("<h", 0) + bytes([0])
    header = element(
        b"\x1A\x45\xDF\xA3",
        uint(b"\x42\x86", 1) + uint(b"\x42\xF7", 1) + uint(b"\x42\xF2", 4)
        + uint(b"\x42\xF3", 8) + string(b"\x42\x82", "webm") + uint(b"\x42\x87", 4)
        + uint(b"\x42\x85", 2),
    )
    info = element(
        b"\x15\x49\xA9\x66",
        uint(b"\x2A\xD7\xB1", 1000000) + element(b"\x44\x89", struct.pack(">d", 120.0))
        + string(b"\x4D\x80", "fastcord-fixture") + string(b"\x57\x41", "fastcord-fixture"),
    )
    video = element(
        b"\xAE",
        uint(b"\xD7", 1) + uint(b"\x73\xC5", 1) + uint(b"\x83", 1) + string(b"\x86", "V_AV1")
        + element(b"\x63\xA2", av1c)
        + element(b"\xE0", uint(b"\xB0", 35) + uint(b"\xBA", 27)),
    )
    audio = element(
        b"\xAE",
        uint(b"\xD7", 2) + uint(b"\x73\xC5", 2) + uint(b"\x83", 2) + string(b"\x86", "A_OPUS")
        + element(b"\x63\xA2", opus_head)
        + element(b"\xE1", element(b"\xB5", struct.pack(">d", 48000.0)) + uint(b"\x9F", 2)),
    )
    tracks = element(b"\x16\x54\xAE\x6B", video + audio)
    cluster1 = element(
        b"\x1F\x43\xB6\x75",
        uint(b"\xE7", 0) + simple_block(1, 0, True, stripped[0])
        + simple_block(2, 0, True, OPUS_PACKETS[0]) + simple_block(2, 20, True, OPUS_PACKETS[1])
        + block_group(1, 33, stripped[1]) + simple_block(2, 40, True, OPUS_PACKETS[2]),
    )
    cluster2 = element(
        b"\x1F\x43\xB6\x75",
        uint(b"\xE7", 60) + simple_block(2, 0, True, OPUS_PACKETS[3])
        + simple_block(1, 6, False, stripped[2])
        + simple_block(2, 20, True, OPUS_PACKETS[4]) + simple_block(2, 40, True, OPUS_PACKETS[5]),
    )
    void = element(b"\xEC", bytes(16))
    segment = element(b"\x18\x53\x80\x67", info + void + tracks + cluster1 + cluster2, True)
    return header + segment


def main():
    outputs = {
        "container-h264-opus.mp4": mp4("opus"),
        "container-h264-aac.mp4": mp4("aac"),
        "container-h264-aac-lc.mp4": mp4("aac-lc"),
        "container-av1-opus.webm": webm(),
    }
    manifest = {"schema": 1, "generator": "gen_container_fixture.py", "files": {}}
    for name, data in outputs.items():
        (HERE / name).write_bytes(data)
        manifest["files"][name] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
        print(name, len(data))
    (HERE / "container-fixture.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
