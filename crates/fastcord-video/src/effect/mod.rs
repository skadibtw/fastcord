//! Camera background effects: free blur and bundled preset backgrounds
//! (issue #85, SPEC §8.9).
//!
//! The effect is a stage between the camera and the encoder on the capture
//! thread: [`Stage::apply`] turns each captured picture into the picture that
//! is both previewed and sent, so the self-view always shows exactly what
//! others get (apart from the preview-only mirror). Only the person-segmentation
//! model is slow, and it runs on its own worker at a reduced size and rate; the
//! capture thread keeps the newest mask and composites every full-rate picture
//! with it.
//!
//! [`Effect::Off`] costs nothing: no model, no worker thread, no copy. The
//! worker starts when an effect is first chosen and is joined and its model
//! freed when the effect goes back to Off (or the camera stops).

